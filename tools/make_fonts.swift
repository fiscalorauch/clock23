// Generates HaloClock/fonts.h — 4-bit anti-aliased bitmap fonts for the round TFT.
// Run from the "OLED Code" folder:  swift tools/make_fonts.swift HaloClock/fonts.h
// Font: Source Sans Pro (SIL Open Font License), from /Library/Fonts.

import CoreGraphics
import CoreText
import Foundation

let fontPath = "/Library/Fonts/SourceSansPro.otf"
let outPath = CommandLine.arguments.count > 1 ? CommandLine.arguments[1] : "fonts.h"

struct Spec { let name: String; let px: CGFloat; let first: Int; let scalars: [UInt32] }

// Slot 127 holds a middle dot (·) so labels like "Maths · 09:00" render.
let ascii = Array(UInt32(32)...UInt32(126)) + [0x00B7]
let digits = Array(UInt32(48)...UInt32(58))  // 0-9 and ':'

let specs = [
    Spec(name: "font13", px: 13, first: 32, scalars: ascii),
    Spec(name: "font16", px: 16, first: 32, scalars: ascii),
    Spec(name: "font21", px: 21, first: 32, scalars: ascii),
    Spec(name: "font26", px: 26, first: 32, scalars: ascii),
    Spec(name: "font34", px: 34, first: 32, scalars: ascii),
    Spec(name: "font40", px: 40, first: 32, scalars: ascii),
    Spec(name: "digits70", px: 70, first: 48, scalars: digits),
]

guard let descs = CTFontManagerCreateFontDescriptorsFromURL(URL(fileURLWithPath: fontPath) as CFURL) as? [CTFontDescriptor],
      let desc = descs.first else {
    fatalError("Could not load \(fontPath)")
}

struct Glyph { var offset = 0; var w = 0; var h = 0; var adv = 0; var xo = 0; var yo = 0 }

func renderGlyph(_ font: CTFont, _ scalar: UInt32) -> (Glyph, [UInt8]) {
    var chars = Array(String(UnicodeScalar(scalar)!).utf16)
    var glyphs = [CGGlyph](repeating: 0, count: chars.count)
    CTFontGetGlyphsForCharacters(font, &chars, &glyphs, chars.count)
    var advance = CGSize.zero
    CTFontGetAdvancesForGlyphs(font, .horizontal, &glyphs, &advance, 1)
    let bb = CTFontGetBoundingRectsForGlyphs(font, .horizontal, &glyphs, nil, 1)

    var g = Glyph()
    g.adv = Int(advance.width.rounded())
    if bb.isEmpty || bb.width < 0.5 { return (g, []) }

    let pad = 2
    let x0 = Int(floor(bb.minX)) - pad, y0 = Int(floor(bb.minY)) - pad
    let W = Int(ceil(bb.maxX)) + pad - x0, H = Int(ceil(bb.maxY)) + pad - y0
    var data = [UInt8](repeating: 0, count: W * H)
    data.withUnsafeMutableBytes { buf in
        let ctx = CGContext(data: buf.baseAddress, width: W, height: H, bitsPerComponent: 8,
                            bytesPerRow: W, space: CGColorSpaceCreateDeviceGray(),
                            bitmapInfo: CGImageAlphaInfo.none.rawValue)!
        ctx.setShouldAntialias(true)
        ctx.setShouldSmoothFonts(false)
        ctx.setFillColor(gray: 1, alpha: 1)
        var pos = CGPoint(x: CGFloat(-x0), y: CGFloat(-y0))
        CTFontDrawGlyphs(font, &glyphs, &pos, 1, ctx)
    }

    // Crop to inked pixels. Bitmap row 0 is the top of the image.
    var top = H, bottom = -1, left = W, right = -1
    for r in 0..<H { for c in 0..<W where data[r * W + c] > 8 {
        top = min(top, r); bottom = max(bottom, r); left = min(left, c); right = max(right, c)
    } }
    if bottom < 0 { return (g, []) }

    g.w = right - left + 1
    g.h = bottom - top + 1
    g.xo = x0 + left
    g.yo = -(y0 + H - top)  // baseline → top row, positive = down

    var nibbles = [UInt8]()
    for r in top...bottom { for c in left...right {
        nibbles.append(UInt8((Int(data[r * W + c]) * 15 + 127) / 255))
    } }
    if nibbles.count % 2 == 1 { nibbles.append(0) }
    var packed = [UInt8]()
    for i in stride(from: 0, to: nibbles.count, by: 2) { packed.append(nibbles[i] << 4 | nibbles[i + 1]) }
    return (g, packed)
}

func hexBytes(_ bytes: [UInt8]) -> String {
    stride(from: 0, to: bytes.count, by: 20).map { i in
        "  " + bytes[i..<min(i + 20, bytes.count)].map { String(format: "0x%02X", $0) }.joined(separator: ",") + ","
    }.joined(separator: "\n")
}

var out = """
// Generated by tools/make_fonts.swift — do not edit by hand.
// Source Sans Pro, SIL Open Font License 1.1. 4-bit alpha, row-major, high nibble first.
#pragma once
#include "font_types.h"


"""

for spec in specs {
    let font = CTFontCreateWithFontDescriptor(desc, spec.px, nil)
    var bitmap = [UInt8]()
    var rows = [String]()
    for s in spec.scalars {
        var (g, bytes) = renderGlyph(font, s)
        g.offset = bitmap.count
        bitmap += bytes
        rows.append("  {\(g.offset),\(g.w),\(g.h),\(g.adv),\(g.xo),\(g.yo)},")
    }
    let ascent = Int(CTFontGetAscent(font).rounded())
    let lineH = Int((CTFontGetAscent(font) + CTFontGetDescent(font)).rounded())
    let capH = Int(CTFontGetCapHeight(font).rounded())
    let last = spec.first + spec.scalars.count - 1
    out += "static const uint8_t \(spec.name)_bmp[] = {\n\(hexBytes(bitmap))\n};\n"
    out += "static const AAGlyph \(spec.name)_glyphs[] = {\n\(rows.joined(separator: "\n"))\n};\n"
    out += "static const AAFont \(spec.name) = {\(spec.name)_bmp, \(spec.name)_glyphs, \(spec.first), \(last), \(ascent), \(capH), \(lineH)};\n\n"
    print("\(spec.name): \(bitmap.count) bytes, ascent \(ascent), cap \(capH), line \(lineH)")
}

try! out.write(toFile: outPath, atomically: true, encoding: .utf8)
print("Wrote \(outPath)")
